package schedule

import (
	"regexp"

	"github.com/hashicorp/terraform-plugin-framework-validators/stringvalidator"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/booldefault"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/schema/validator"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

// timePattern matches the H:MM / HH:MM 24-hour form NodePing expects. Catching
// "6:0" or "25:00" at plan time is much cheaper than catching it at apply time.
var timePattern = regexp.MustCompile(`^(?:[01]?[0-9]|2[0-3]):[0-5][0-9]$`)

const timePatternDescription = "must be a 24-hour time of the form H:MM or HH:MM, for example \"6:00\" or \"18:30\""

// ScheduleResourceModel is the state for a nodeping_schedule.
//
// The seven days are separate optional attributes rather than a map: the key
// set is fixed and known, so a typo like "monady" is a plan-time error instead
// of a silently ignored day.
type ScheduleResourceModel struct {
	ID         types.String `tfsdk:"id"`
	CustomerID types.String `tfsdk:"customer_id"`
	Monday     *DayModel    `tfsdk:"monday"`
	Tuesday    *DayModel    `tfsdk:"tuesday"`
	Wednesday  *DayModel    `tfsdk:"wednesday"`
	Thursday   *DayModel    `tfsdk:"thursday"`
	Friday     *DayModel    `tfsdk:"friday"`
	Saturday   *DayModel    `tfsdk:"saturday"`
	Sunday     *DayModel    `tfsdk:"sunday"`
}

// DayModel is one day's notification window.
type DayModel struct {
	Time1    types.String `tfsdk:"time1"`
	Time2    types.String `tfsdk:"time2"`
	Exclude  types.Bool   `tfsdk:"exclude"`
	Disabled types.Bool   `tfsdk:"disabled"`
	AllDay   types.Bool   `tfsdk:"allday"`
}

// day returns the model for the named day, or nil when the day is not
// configured.
func (m *ScheduleResourceModel) day(name string) *DayModel {
	switch name {
	case "monday":
		return m.Monday
	case "tuesday":
		return m.Tuesday
	case "wednesday":
		return m.Wednesday
	case "thursday":
		return m.Thursday
	case "friday":
		return m.Friday
	case "saturday":
		return m.Saturday
	case "sunday":
		return m.Sunday
	}
	return nil
}

func (m *ScheduleResourceModel) setDay(name string, day *DayModel) {
	switch name {
	case "monday":
		m.Monday = day
	case "tuesday":
		m.Tuesday = day
	case "wednesday":
		m.Wednesday = day
	case "thursday":
		m.Thursday = day
	case "friday":
		m.Friday = day
	case "saturday":
		m.Saturday = day
	case "sunday":
		m.Sunday = day
	}
}

func ScheduleSchema() schema.Schema {
	return schema.Schema{
		Description: "Manages a NodePing notification schedule.",
		MarkdownDescription: `
Manages a NodePing notification schedule.

A schedule names a weekly notification window. Contact addresses reference it by
name to limit when they are paged.

The NodePing schedules endpoint has no POST: ` + "`PUT`" + ` both creates and
updates, and the identifier is chosen by you rather than generated by NodePing.
That makes ` + "`id`" + ` a required argument. Changing it destroys the old
schedule and creates a new one.

## Example Usage

` + "```hcl" + `
resource "nodeping_schedule" "business_hours" {
  id = "BusinessHours"

  monday    = { time1 = "8:00", time2 = "18:00" }
  tuesday   = { time1 = "8:00", time2 = "18:00" }
  wednesday = { time1 = "8:00", time2 = "18:00" }
  thursday  = { time1 = "8:00", time2 = "18:00" }
  friday    = { time1 = "8:00", time2 = "17:00" }
  saturday  = { disabled = true }
  sunday    = { disabled = true }
}
` + "```" + `

## Import

Schedules are imported by ID:

` + "```shell" + `
terraform import nodeping_schedule.business_hours BusinessHours
` + "```" + `

For SubAccount schedules, use ` + "`customer_id:schedule_id`" + `.
`,
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Description: "The schedule name. You choose this value; NodePing does not generate it. " +
					"Changing it forces a new schedule to be created.",
				Required: true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.RequiresReplace(),
				},
				Validators: []validator.String{
					stringvalidator.LengthBetween(1, 100),
					stringvalidator.RegexMatches(
						regexp.MustCompile(`^[^/?#\s][^/?#]*$`),
						"must not contain '/', '?' or '#', and must not start with whitespace",
					),
				},
			},
			"customer_id": schema.StringAttribute{
				Description: "The customer ID (SubAccount ID) that owns this schedule. " +
					"Set this to manage a schedule that belongs to a SubAccount. " +
					"Changing it forces a new schedule to be created.",
				Optional: true,
				Computed: true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.RequiresReplace(),
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			"monday":    dayAttribute("Monday"),
			"tuesday":   dayAttribute("Tuesday"),
			"wednesday": dayAttribute("Wednesday"),
			"thursday":  dayAttribute("Thursday"),
			"friday":    dayAttribute("Friday"),
			"saturday":  dayAttribute("Saturday"),
			"sunday":    dayAttribute("Sunday"),
		},
	}
}

func dayAttribute(day string) schema.SingleNestedAttribute {
	return schema.SingleNestedAttribute{
		Description: "Notification window for " + day + ". Omit the block to leave " + day + " unscheduled.",
		Optional:    true,
		Attributes: map[string]schema.Attribute{
			"time1": schema.StringAttribute{
				Description: "Start of the notification span, in 24-hour H:MM or HH:MM form (for example \"8:00\").",
				Optional:    true,
				Computed:    true,
				Validators: []validator.String{
					stringvalidator.RegexMatches(timePattern, timePatternDescription),
				},
			},
			"time2": schema.StringAttribute{
				Description: "End of the notification span, in 24-hour H:MM or HH:MM form (for example \"18:00\").",
				Optional:    true,
				Computed:    true,
				Validators: []validator.String{
					stringvalidator.RegexMatches(timePattern, timePatternDescription),
				},
			},
			"exclude": schema.BoolAttribute{
				Description: "Invert the span: notify all day except between time1 and time2.",
				Optional:    true,
				Computed:    true,
				Default:     booldefault.StaticBool(false),
			},
			"disabled": schema.BoolAttribute{
				Description: "Disable notifications for this day entirely.",
				Optional:    true,
				Computed:    true,
				Default:     booldefault.StaticBool(false),
			},
			"allday": schema.BoolAttribute{
				Description: "Enable notifications for the whole day.",
				Optional:    true,
				Computed:    true,
				Default:     booldefault.StaticBool(false),
			},
		},
	}
}
